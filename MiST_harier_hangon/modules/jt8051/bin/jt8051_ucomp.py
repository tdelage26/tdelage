#!/usr/bin/env python3
#
#

import os, re, sys
from collections import defaultdict

d = sys.argv[1] if len(sys.argv) > 1 else '.'
uc = [l.strip() for l in open(os.path.join(d, 'jt8051.uc')) if l.strip()]
vh = open(os.path.join(d, 'jt8051.vh')).read()
par = open(os.path.join(d, 'jt8051_param.vh')).read()

W = len(uc[0])
assert W == 48, W
ZERO = '0' * W

used = defaultdict(int)
for a, w in enumerate(uc):
    if w != ZERO:
        b, s = a >> 6, a & 63
        used[b] = max(used[b], s + 1)

def seqa(name):
    m = re.search(r'localparam\s+%s\s*=\s*15\'h([0-9A-Fa-f]+)' % name, par)
    return int(m.group(1), 16)

FETCH0 = seqa('FETCH0_SEQA')
ISR    = seqa('ISR_SEQA')

jsr = []
for m in re.finditer(r'(\w+_JSR):\s*begin\s*jsr_en=1;\s*jsr_ua\s*=\s*([^;]+);', vh):
    name, expr = m.group(1), m.group(2).strip()
    if expr == 'jsr_ret':
        jsr.append((name, None))
    else:
        mm = re.match(r"15'h([0-9A-Fa-f]+)\*15'd64", expr)
        assert mm, expr
        jsr.append((name, int(mm.group(1), 16) << 6))

base = {}
store = [ZERO]
for b in sorted(used):
    base[b] = len(store)
    n = min(64, used[b] + 1)
    store += uc[(b << 6):(b << 6) + n]
N = len(store)
CPCW = max(1, (N - 1).bit_length())

def cmap(a):
    b, s = a >> 6, a & 63
    assert b in base, 'entry point %x is not in the microcode' % a
    assert s < min(64, used[b] + 1)
    return base[b] + s

words = sorted(set(store), key=lambda w: (w != ZERO, w))
assert words[0] == ZERO and len(words) <= 256, len(words)
widx = {w: i for i, w in enumerate(words)}

with open(os.path.join(d, 'jt8051_cidx.hex'), 'w') as f:
    for w in store:
        f.write('%02X\n' % widx[w])

fields = re.findall(r'^assign\s+\w+\s*=\s*ucode_data\[[^\]]+\];', vh, re.M)
assert len(fields) == 18, len(fields)

o = []
o.append('// Generated by modules/jt8051/bin/jt8051_ucomp.py from jt8051.uc -- do not edit')
o.append('// %d stored words of %d, %d distinct, cpc %d bits' % (N, len(uc), len(words), CPCW))
o.append('localparam CPCW = %d;' % CPCW)
o.append('reg              jsr_en;')
o.append('reg  [CPCW-1:0]  cpc, cpc_nx, cjsr_ret, cjsr_ua;')
o.append('reg  [     7:0]  uidx;')
o.append('reg  [     7:0]  uidx_rom[0:%d];' % (N - 1))
o.append('reg  [    47:0]  ucode_data;')
o.append('')
o.append('initial begin')
o.append('    $readmemh("jt8051_cidx.hex",uidx_rom);')
o.append('end')
o.append('')
o.append("localparam [CPCW-1:0] CFETCH0 = %d'd%d, CISR = %d'd%d;" % (CPCW, cmap(FETCH0), CPCW, cmap(ISR)))
o.append('')
o.append('always @* begin')
o.append('    case( uidx )')
for i, w in enumerate(words):
    if i == 0: continue
    o.append("        8'd%d: ucode_data = 48'h%012X;" % (i, int(w, 2)))
o.append("        default: ucode_data = 48'h0;")
o.append('    endcase')
o.append('end')
o.append('')
o += fields
o.append('')
o.append('function [CPCW-1:0] op_base( input [7:0] op );')
o.append('    case( op )')
for op in range(256):
    o.append("        8'h%02X: op_base = %d'd%d;" % (op, CPCW, cmap(op << 6)))
o.append('    endcase')
o.append('endfunction')
o.append('')
o.append('always @* begin')
o.append('    case( jsr_sel )')
for name, t in jsr:
    if t is None:
        o.append('        %-14s begin jsr_en=1; cjsr_ua = cjsr_ret; end' % (name + ':'))
    else:
        o.append("        %-14s begin jsr_en=1; cjsr_ua = %d'd%d; end" % (name + ':', CPCW, cmap(t)))
o.append("        default:       begin jsr_en=0; cjsr_ua = 0; end")
o.append('    endcase')
o.append('end')
open(os.path.join(d, 'jt8051_c.vh'), 'w').write('\n'.join(o) + '\n')
print('jt8051_ucomp: %d words stored (%d distinct), cpc %d bits' % (N, len(words), CPCW))
